CREATE SCHEMA IF NOT EXISTS diplom_all;

CREATE TABLE IF NOT EXISTS diplom_all."user" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(256) NOT NULL,
    password VARCHAR(256) NOT NULL,
    user_type VARCHAR(16) NOT NULL DEFAULT 'user'
);

CREATE TABLE IF NOT EXISTS diplom_all.created_user (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(256) NOT NULL,
    date_time TIMESTAMP NOT NULL,
    user_agent VARCHAR NOT NULL,
    ip VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.login_attempt (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(256) NOT NULL,
    date_time TIME WITH TIME ZONE NOT NULL,
    user_agent VARCHAR NOT NULL,
    ip VARCHAR NOT NULL,
    is_success BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.user_group (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(256) NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.user_group_user (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user INTEGER NOT NULL,
    id_user_group INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.product_category (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(512) NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.product (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(512) NOT NULL,
    id_product_category INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all." unit_of_measurement" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.storage_place (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.user_group_product (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user_group INTEGER NOT NULL,
    id_product INTEGER NOT NULL,
    product_name VARCHAR(512) NOT NULL,
    id_unit_of_measurement INTEGER NOT NULL,
    quantity NUMERIC NOT NULL,
    best_before DATE NOT NULL,
    purchased_on DATE,
    id_product_category INTEGER NOT NULL,
    "Id_storage_place" INTEGER,
    is_deleted BOOLEAN,
    is_consumed BOOLEAN,
    is_wasted BOOLEAN,
    is_over BOOLEAN,
    added_at TIMESTAMP WITH TIME ZONE,
    id_user INTEGER
);

CREATE TABLE IF NOT EXISTS diplom_all.user_group_purchase (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user_group INTEGER NOT NULL,
    plan_date DATE,
    actual_date TIMESTAMP,
    create_date_time TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.user_group_purchase_product (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user_group INTEGER NOT NULL,
    id_product INTEGER NOT NULL,
    product_name VARCHAR(512) NOT NULL,
    id_unit_of_measurement INTEGER NOT NULL,
    quantity NUMERIC NOT NULL,
    id_product_category INTEGER NOT NULL,
    id_user_group_purchase INTEGER NOT NULL,
    create_date_time TIMESTAMP NOT NULL,
    is_deleted BOOLEAN,
    is_purchased BOOLEAN
);

CREATE TABLE IF NOT EXISTS diplom_all.user_group_product_consumption (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user_group_product INTEGER NOT NULL,
    quantity NUMERIC NOT NULL,
    date_time TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.user_group_product_waste (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user_group_product INTEGER NOT NULL,
    quantity NUMERIC NOT NULL,
    date_time TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.feedback (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user INTEGER NOT NULL,
    message TEXT NOT NULL,
    date_time TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.news (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    date_time TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS diplom_all.news_read (
    id_user INTEGER NOT NULL,
    id_news INTEGER NOT NULL,
    PRIMARY KEY (id_user, id_news)
);

CREATE TABLE IF NOT EXISTS diplom_all.feedback_photo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_feedback INTEGER NOT NULL,
    content BYTEA NOT NULL,
    content_type VARCHAR(64) NOT NULL
);

