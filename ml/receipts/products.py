def _shelf_life() -> dict[str, int]:
    life: dict[str, int] = {}
    for days, names in _SHELF_GROUPS:
        for name in names:
            if name in life:
                raise ValueError(f"Срок указан дважды: {name}")
            life[name] = days
    missing = [name for name in BASE_PRODUCTS if name not in life]
    extra = [name for name in life if name not in set(BASE_PRODUCTS)]
    if missing or extra:
        raise ValueError(f"Срок не сходится с каталогом: нет {missing}, лишние {extra}")
    return life


