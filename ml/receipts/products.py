def _categories() -> dict[str, str]:
    found: dict[str, str] = {}
    for category, names in _CATEGORY_GROUPS:
        for name in names:
            if name in found:
                raise ValueError(f"Категория указана дважды: {name}")
            found[name] = category
    missing = [name for name in BASE_PRODUCTS if name not in found]
    extra = [name for name in found if name not in set(BASE_PRODUCTS)]
    if missing or extra:
        raise ValueError(f"Категория не сходится с каталогом: нет {missing}, лишние {extra}")
    return found


CATEGORIES: dict[str, str] = _categories()


def pantry_category(name: str) -> str | None:
    """Категория кладовой по базовому имени. Процент в названии на категорию не влияет."""
    import re

    base = re.sub(r"\s+\d+(?:[.,]\d+)?%$", "", name.strip().lower().replace("ё", "е"))
    return CATEGORIES.get(base)
